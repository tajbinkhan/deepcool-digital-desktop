/** Picks the saved language, else the system language, else English. */
export function resolveLang(saved: string): Lang {
  const codes = LANGUAGES.map((l) => l.code) as string[];
  if (codes.includes(saved)) return saved as Lang;
  const system = (navigator.language || "en").slice(0, 2).toLowerCase();
  return (codes.includes(system) ? system : "en") as Lang;
}

export function translate(lang: Lang, key: Key, vars: Record<string, string> = {}): string {
  let text = dictionaries[lang][key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, value);
  return text;
}

/** Every key each language is missing; used by a check script. */
export function missingKeys(): Record<string, string[]> {
  const result: Record<string, string[]> = {};
  for (const [code, dict] of Object.entries(dictionaries)) {
    if (code === "en") continue;
    const missing = (Object.keys(en) as Key[]).filter(
      (k) => !(k in dict) && !["cpu", "gpu", "mode.cpu", "mode.gpu", "celsius", "fahrenheitUnit"].includes(k),
    );
    if (missing.length) result[code] = missing;
  }
  return result;
}
